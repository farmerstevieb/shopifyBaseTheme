/**
 * generate-theme-assets.js
 * Generates dist/snippets/theme_assets.liquid after webpack build.
 * Also generates dist/snippets/eager-chunks.liquid with discovered eager-load chunks.
 *
 * This bootstraps the webpack runtime on Shopify by:
 *   1. Setting the CDN public path so lazy chunks load correctly
 *   2. Loading main.min.css and main.min.js via Liquid asset_url
 *   3. Eagerly loading any chunk named in EAGER_CHUNK_NAMES to optimize first paint
 */

const fs = require("fs");
const path = require("path");

const DIST_DIR = path.join(__dirname, "../dist/assets");
const OUTPUT_ASSETS = path.join(__dirname, "../dist/snippets/theme_assets.liquid");
const OUTPUT_EAGER = path.join(__dirname, "../dist/snippets/eager-chunks.liquid");

// Chunks to eagerly load, by their webpackChunkName (see the `import(/*
// webpackChunkName: "..." */ ...)` call sites in src/js) -- not by numeric
// chunk id. webpack.config.js forces optimization.chunkIds: "named" plus a
// content hash in the filename ([name].[contenthash:8].js), so a chunk's
// *name* is stable across rebuilds even though its exact filename isn't --
// matching by name is what survives a rebuild; matching by numeric id does
// not (numeric ids are reassigned per-build and are exactly what
// chunkIds: "named" was introduced to stop relying on).
//
// Deliberately empty by default. This replaces an older hardcoded numeric
// EAGER_CHUNK_IDS list ([1093, 4009, 2735, 9321, 7592]) that predates the
// named-chunk-ids change above and can no longer be mapped back to specific
// chunk names. None of src/js's current split chunks (side-effects,
// recently-viewed, countdown-timer, cookie-consent, ecomplete-search,
// newsletter-popup, compare, upsell, shop-the-look, lazyload, slider,
// body-scroll-lock-upgrade) are self-evidently "the same 5" the old numeric
// ids pointed at -- and header/dialog/product/accountDialog, the actual
// drawer/cart/account/nav components this feature's docstring describes,
// are statically imported into main.min.js already, not split chunks at
// all. Populate this list deliberately with whichever chunk names should
// genuinely eager-load for first paint, rather than guessing.
const EAGER_CHUNK_NAMES = [];

/**
 * Scan dist/assets for the actual built filename of each named chunk (now
 * content-hashed, e.g. "compare.a1b2c3d4.js") and its CSS counterpart.
 * Returns array of {js, css} objects with actual filenames.
 */
function discoverEagerChunks() {
  if (!fs.existsSync(DIST_DIR)) {
    console.warn("⚠ dist/assets not found, eager chunks will be empty");
    return [];
  }

  const files = fs.readdirSync(DIST_DIR);
  const eagerChunks = [];

  EAGER_CHUNK_NAMES.forEach((name) => {
    const jsPattern = new RegExp(`^${name}\\.[0-9a-f]+\\.js$`);
    const cssPattern = new RegExp(`^${name}\\.[0-9a-f]+\\.css$`);
    const jsFile = files.find((f) => jsPattern.test(f));
    if (!jsFile) {
      console.warn(`⚠ Eager chunk "${name}" not found in dist/assets — check the name matches its webpackChunkName`);
      return;
    }
    const cssFile = files.find((f) => cssPattern.test(f)) || null;
    eagerChunks.push({ js: jsFile, css: cssFile });
  });

  return eagerChunks;
}

const themeAssetsContent = `{% # theme-check-disable %}
{%- comment -%}
  Loads webpack-bundled assets for the theme.
  Auto-generated by scripts/generate-theme-assets.js — do not edit directly.

  Usage:
  {%- render 'theme_assets', import_map: true -%}
  {%- render 'theme_assets' with 'main.min.js', preload: true, is_module: false -%}
  {%- render 'theme_assets' with 'main.min.css', preload: true -%}
{%- endcomment -%}

{%- if import_map == true -%}
  {%- assign _js_url = 'main.min.js' | asset_url -%}
  {%- assign _public_path = _js_url | split: 'main.min.js' | first -%}
  <script data-public-path="{{ _public_path }}">{}</script>

{%- elsif theme_assets == 'main.min.js' -%}
  {%- if preload -%}
    <link rel="preload" href="{{ 'main.min.js' | asset_url }}" as="script">
  {%- endif -%}
  {%- if is_module -%}
    <script type="module" src="{{ 'main.min.js' | asset_url }}"></script>
  {%- else -%}
    <script defer src="{{ 'main.min.js' | asset_url }}"></script>
  {%- endif -%}

{%- elsif theme_assets == 'main.min.css' -%}
  {%- if preload -%}
    <link rel="preload" href="{{ 'main.min.css' | asset_url }}" as="style">
  {%- endif -%}
  <link rel="stylesheet" href="{{ 'main.min.css' | asset_url }}">

{%- elsif theme_assets != blank -%}
  <link rel="stylesheet" href="{{ theme_assets | asset_url }}">

{%- endif -%}
`;

fs.writeFileSync(OUTPUT_ASSETS, themeAssetsContent);
console.log("✓ Generated theme_assets.liquid");

// Generate eager-chunks.liquid
const eagerChunks = discoverEagerChunks();
let eagerChunksContent = `{% # theme-check-disable %}
{%- comment -%}
  Eagerly loads webpack chunks named in EAGER_CHUNK_NAMES for first-paint
  optimization, instead of waiting for their lazy import() to fire.
  Auto-generated by scripts/generate-theme-assets.js — do not edit directly.

  Automatically discovers and loads the actual chunk filenames (including
  their content hash) from the webpack build, for both JS and CSS variants.
  Updates automatically on each build.
{%- endcomment -%}

`;

if (eagerChunks.length > 0) {
  eagerChunks.forEach(chunk => {
    // Only eagerly load JS chunks. CSS chunks are lazy-loaded by webpack's
    // runtime via its own dynamic import() handling.
    eagerChunksContent += `<script src="{{ '${chunk.js}' | asset_url }}" defer></script>\n`;
  });
} else {
  eagerChunksContent += `{%- comment -%}No eager chunks discovered{%- endcomment -%}\n`;
}

fs.writeFileSync(OUTPUT_EAGER, eagerChunksContent);
console.log(`✓ Generated eager-chunks.liquid (${eagerChunks.length} chunks)`);

// Log discovered chunks for verification
if (eagerChunks.length > 0) {
  console.log("\nEager chunks discovered:");
  eagerChunks.forEach(chunk => {
    const cssInfo = chunk.css ? ` + ${chunk.css}` : "";
    console.log(`  - ${chunk.js}${cssInfo}`);
  });
}
